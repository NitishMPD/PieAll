/** Picks the most relevant icon for an app command from its title; generic when unsure. */
export function iconFor(title: string): IconName {
  const text = title.toLowerCase();
  return rules.find(([pattern]) => pattern.test(text))?.[1] ?? "command";
}

export function Icon({ name, size = 22 }: { name: string; size?: number }) {
  const Glyph =
    (pack as Record<string, LucideIcon>)[name.toLowerCase()] ?? Command;
  return <Glyph size={size} strokeWidth={1.7} aria-hidden="true" />;
}
